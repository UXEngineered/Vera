export interface ReviewState {
  approved: Record<string, string>; // section id → ISO time
  edits: Record<string, string>; // claim id → edited text
}

export function toMarkdown(d: Deliverable, title: string, client: string, review: ReviewState, model: string): string {
  const approvedCount = d.sections.filter((s) => review.approved[s.id]).length;
  const final = approvedCount === d.sections.length;
  const lines = [
    `# ${title}: ${client}`,
    ``,
    final
      ? `> **Approved.** Every section was reviewed and approved by a person.`
      : `> **Draft for review.** ${approvedCount} of ${d.sections.length} sections approved. VERA proposes; a person decides.`,
    `> Readiness: ${READINESS[d.readiness].label}. Generated by VERA (${model}).`,
    ``,
  ];
  for (const s of d.sections) {
    lines.push(`## ${s.title}${review.approved[s.id] ? " ✓" : " (draft)"}`, ``);
    if (s.claims.length === 0) lines.push(`_${s.note ?? "No supportable claims yet."}_`, ``);
    for (const c of s.claims) {
      const text = review.edits[c.id] ?? c.text;
      const action = c.action ? ` · ${c.action}` : "";
      const edited = review.edits[c.id] ? " · edited" : "";
      lines.push(`- ${text} _[${confidenceLabel(c.confidence)}${action}${edited} · ${c.evidence_ids.join(", ")}]_`);
    }
    lines.push(``);
  }
  if (d.conflicts.length) {
    lines.push(`## Conflicts in the evidence`, ``);
    for (const c of d.conflicts) lines.push(`- **${c.evidence_ids.join(" vs ")}**: ${c.description} _Resolve by:_ ${c.how_to_resolve}`);
    lines.push(``);
  }
  if (d.gaps.length) {
    lines.push(`## Evidence gaps`, ``);
    for (const g of d.gaps) lines.push(`- **${g.missing}**: ${g.why_it_matters} _Would raise confidence:_ ${g.would_raise_confidence}`);
    lines.push(``);
  }
  return lines.join("\n");
}
