/** Events streamed from /api/generate (pipeline events plus server meta). */
export type StreamEvent =
  | { type: "meta"; recorded: boolean; notice?: string; log: EvidenceLog }
  | { type: "start"; run_id: string; deliverable: string; provider: string; model: string; prompt_versions: string[]; profile: EvidenceProfile }
  | { type: "attempt"; attempt: number; max_attempts: number }
  | { type: "draft_section"; attempt: number; section: RawSection }
  | { type: "retry"; attempt: number; issues: CheckIssue[] }
  | { type: "done"; deliverable: Deliverable; attempts: number; usage: { input_tokens: number; output_tokens: number; latency_ms: number } }
  | { type: "failed"; message: string; issues: CheckIssue[]; attempts: number }
  | { type: "error"; message: string };

export class RequestError extends Error {
  constructor(message: string, readonly issues?: { path: string; message: string }[]) {
    super(message);
  }
}

export async function streamGenerate(
  body: unknown,
  onEvent: (e: StreamEvent) => void,
  signal: AbortSignal,
): Promise<void> {
  const res = await fetch("/api/generate", {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify(body),
    signal,
  });
  if (!res.ok || !res.body) {
    const err = (await res.json().catch(() => ({ error: `Request failed (${res.status})` }))) as { error: string; issues?: { path: string; message: string }[] };
    throw new RequestError(err.error, err.issues);
  }
  const reader = res.body.pipeThrough(new TextDecoderStream()).getReader();
  let buffer = "";
  for (;;) {
    const { value, done } = await reader.read();
    if (done) break;
    buffer += value;
    let idx;
    while ((idx = buffer.indexOf("\n\n")) >= 0) {
      const chunk = buffer.slice(0, idx);
      buffer = buffer.slice(idx + 2);
      if (chunk.startsWith("data: ")) onEvent(JSON.parse(chunk.slice(6)));
    }
  }
}

